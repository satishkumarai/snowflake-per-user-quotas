-- PUQ Validation: Comprehensive deployment check
USE ROLE ACCOUNTADMIN;

-- Section 1: Environment
SELECT IFF(COUNT(*) = 1, 'PASS', 'FAIL') AS T_DATABASE
FROM INFORMATION_SCHEMA.DATABASES WHERE DATABASE_NAME = 'PUQ_GOVERNANCE_DB';

SELECT IFF(COUNT(*) = 3, 'PASS', 'FAIL') AS T_SCHEMAS
FROM PUQ_GOVERNANCE_DB.INFORMATION_SCHEMA.SCHEMATA
WHERE SCHEMA_NAME IN ('QUOTAS', 'TAGS', 'ACTIONS');

-- Section 2: User and Tags
SELECT
    IFF(SYSTEM$GET_TAG('PUQ_GOVERNANCE_DB.TAGS.COST_CENTER', 'PUQ_DEMO_USER', 'USER') = 'engineering', 'PASS', 'FAIL') AS T_TAG_COST_CENTER,
    IFF(SYSTEM$GET_TAG('PUQ_GOVERNANCE_DB.TAGS.USAGE_TIER', 'PUQ_DEMO_USER', 'USER') = 'standard', 'PASS', 'FAIL') AS T_TAG_USAGE_TIER,
    IFF(SYSTEM$GET_TAG('PUQ_GOVERNANCE_DB.TAGS.DEPARTMENT', 'PUQ_DEMO_USER', 'USER') = 'data-science', 'PASS', 'FAIL') AS T_TAG_DEPARTMENT;

-- Section 3: Quota Configuration
USE ROLE PUQ_QUOTA_ADMIN_ROLE;
USE SCHEMA PUQ_GOVERNANCE_DB.QUOTAS;

CALL PUQ_AI_STANDARD_QUOTA!GET_CONFIG();
-- Expected: PER_USER_LIMIT=100, PER_USER_LIMIT_DAILY=10, BLOCK_ENFORCEMENT_ENABLED=TRUE, REFRESH_TIER=TIER_1H

CALL PUQ_AI_HIGH_TIER_QUOTA!GET_CONFIG();
-- Expected: PER_USER_LIMIT=500, PER_USER_LIMIT_DAILY=50, BLOCK_ENFORCEMENT_ENABLED=TRUE

CALL PUQ_WH_STANDARD_QUOTA!GET_CONFIG();
-- Expected: PER_USER_LIMIT=50, PER_USER_LIMIT_DAILY=5

-- Section 4: Notifications
CALL PUQ_AI_STANDARD_QUOTA!GET_NOTIFICATION_THRESHOLDS();
-- Expected: 4 thresholds (50 PROJECTED, 80 PROJECTED, 90 ACTUAL, 100 ACTUAL)

CALL PUQ_WH_STANDARD_QUOTA!GET_NOTIFICATION_THRESHOLDS();
-- Expected: 3 thresholds (60 PROJECTED, 80 PROJECTED, 100 ACTUAL)

-- Section 5: Custom Actions
CALL PUQ_WH_STANDARD_QUOTA!GET_CUSTOM_ACTIONS();
-- Expected: DISABLE_USERS_BY_ID at 100% ACTUAL

CALL PUQ_WH_STANDARD_QUOTA!CONFIRM_CUSTOM_ACTIONS_ACCESS();
-- Expected: Success

CALL PUQ_WH_STANDARD_QUOTA!GET_CYCLE_START_ACTION();
-- Expected: REENABLE_QUOTA_USERS configured

-- Section 6: Scope & Enforcement
CALL PUQ_AI_STANDARD_QUOTA!GET_QUOTA_SCOPE();
-- Expected: INTERSECTION of COST_CENTER=engineering, USAGE_TIER=standard

CALL PUQ_AI_STANDARD_QUOTA!GET_USERS();
-- Expected: PUQ_DEMO_USER (may lag ~2h due to TAG_REFERENCES)

CALL PUQ_AI_STANDARD_QUOTA!GET_ACTIVE_BLOCKS();
-- Expected: Empty (no usage yet)

SELECT 'PUQ VALIDATION COMPLETE' AS STATUS;
