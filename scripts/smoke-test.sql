USE ROLE ACCOUNTADMIN;

SELECT IFF(COUNT(*) = 1, 'PASS', 'FAIL') AS PUQ_DB_EXISTS
FROM INFORMATION_SCHEMA.DATABASES WHERE DATABASE_NAME = 'PUQ_GOVERNANCE_DB';

SELECT IFF(COUNT(*) = 3, 'PASS', 'FAIL') AS PUQ_SCHEMAS_EXIST
FROM PUQ_GOVERNANCE_DB.INFORMATION_SCHEMA.SCHEMATA
WHERE SCHEMA_NAME IN ('QUOTAS', 'TAGS', 'ACTIONS');

SHOW USERS LIKE 'PUQ_DEMO_USER';
SHOW WAREHOUSES LIKE 'PUQ_TEST_WH';

