-- PUQ 10: Validation Tests
-- =============================================================================
-- Run after deployment to confirm all PUQ components are configured correctly.
-- ROLE REQUIRED: ACCOUNTADMIN and PUQ_QUOTA_ADMIN_ROLE
-- =============================================================================

USE ROLE ACCOUNTADMIN;

-- T1: Database exists.
SELECT IFF(COUNT(*) = 1, 'PASS', 'FAIL') AS T1_DATABASE
FROM INFORMATION_SCHEMA.DATABASES WHERE DATABASE_NAME = 'PUQ_GOVERNANCE_DB';

-- T2: Schemas exist.
SELECT IFF(COUNT(*) = 3, 'PASS', 'FAIL') AS T2_SCHEMAS
FROM PUQ_GOVERNANCE_DB.INFORMATION_SCHEMA.SCHEMATA
WHERE SCHEMA_NAME IN ('QUOTAS', 'TAGS', 'ACTIONS');

-- T3: Tags on PUQ_DEMO_USER.
SELECT
    IFF(SYSTEM$GET_TAG('PUQ_GOVERNANCE_DB.TAGS.COST_CENTER', 'PUQ_DEMO_USER', 'USER') = 'engineering', 'PASS', 'FAIL') AS T3_CC,
    IFF(SYSTEM$GET_TAG('PUQ_GOVERNANCE_DB.TAGS.USAGE_TIER', 'PUQ_DEMO_USER', 'USER') = 'standard', 'PASS', 'FAIL') AS T3_TIER,
    IFF(SYSTEM$GET_TAG('PUQ_GOVERNANCE_DB.TAGS.DEPARTMENT', 'PUQ_DEMO_USER', 'USER') = 'data-science', 'PASS', 'FAIL') AS T3_DEPT;

-- T4: Quota configs.
USE ROLE PUQ_QUOTA_ADMIN_ROLE;
USE SCHEMA PUQ_GOVERNANCE_DB.QUOTAS;
CALL PUQ_AI_STANDARD_QUOTA!GET_CONFIG();
CALL PUQ_AI_HIGH_TIER_QUOTA!GET_CONFIG();
CALL PUQ_WH_STANDARD_QUOTA!GET_CONFIG();

-- T5: Notifications.
CALL PUQ_AI_STANDARD_QUOTA!GET_NOTIFICATION_THRESHOLDS();
CALL PUQ_WH_STANDARD_QUOTA!GET_NOTIFICATION_THRESHOLDS();

-- T6: Custom actions.
CALL PUQ_WH_STANDARD_QUOTA!GET_CUSTOM_ACTIONS();
CALL PUQ_WH_STANDARD_QUOTA!CONFIRM_CUSTOM_ACTIONS_ACCESS();
CALL PUQ_WH_STANDARD_QUOTA!GET_CYCLE_START_ACTION();

-- T7: User scope.
CALL PUQ_AI_STANDARD_QUOTA!GET_QUOTA_SCOPE();
CALL PUQ_AI_STANDARD_QUOTA!GET_USERS();

-- T8: Block enforcement.
CALL PUQ_AI_STANDARD_QUOTA!GET_ACTIVE_BLOCKS();

SELECT 'PUQ VALIDATION COMPLETE' AS STATUS;
