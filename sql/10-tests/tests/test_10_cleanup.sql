USE ROLE ACCOUNTADMIN;

SELECT IFF(COUNT(*) = 0, 'PASS', 'FAIL') AS T10_DB_REMOVED
FROM INFORMATION_SCHEMA.DATABASES WHERE DATABASE_NAME = 'PUQ_GOVERNANCE_DB';

SHOW USERS LIKE 'PUQ_DEMO_USER';
SELECT IFF(COUNT(*) = 0, 'PASS', 'FAIL') AS T10_USER_REMOVED
FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));

SHOW ROLES LIKE 'PUQ_%_ROLE';
SELECT IFF(COUNT(*) = 0, 'PASS', 'FAIL') AS T10_ROLES_REMOVED
FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));
